// Dev-time generator for app/map/basemap-layers.js. Not loaded by the app.
// Usage: node app/map/generate-basemap-layers.mjs <path to npm-packed @protomaps/basemaps 5.7.2 package dir>
// Example: npm pack @protomaps/basemaps@5.7.2 && tar -xzf protomaps-basemaps-5.7.2.tgz, then pass ./package.
// The output targets the Protomaps basemap v4 tile schema. Our own adjustments (colors tuned for a
// topo reading, terrain-first POI policy) live in the TOPO flavor below and in style.js.
import {writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {pathToFileURL, fileURLToPath} from 'node:url';

const pkg = process.argv[2];
if (!pkg) throw new Error('usage: node generate-basemap-layers.mjs <@protomaps/basemaps package dir>');
const {layers, LIGHT} = await import(pathToFileURL(resolve(pkg, 'dist/esm/index.js')).href);

// Topo flavor: warmer paper earth, clearly green forest (open vs treed terrain matters for skiing),
// white glaciers/snowfields, saturated water, darker labels for outdoor contrast.
const TOPO = {
  ...LIGHT,
  background: '#e9e5dc', earth: '#efebe3',
  wood_a: '#cfe3c6', wood_b: '#a9d39a', scrub_a: '#e0e8d2', scrub_b: '#c8dcb4',
  park_a: '#e3ead9', park_b: '#cfe0c2', glacier: '#f7fbff', water: '#6fb7e4',
  buildings: '#d4cfc6', railway: '#8d9497', boundaries: '#8c7f95',
  roads_label_minor: '#4f4a4c', roads_label_major: '#3f3a3c',
  subplace_label: '#4a4a4a', city_label: '#262626', state_label: '#6b6b6b', country_label: '#6b6b6b',
  landcover: {...LIGHT.landcover, forest: 'rgba(178, 214, 168, 1)', grassland: 'rgba(226, 238, 210, 1)',
    barren: 'rgba(240, 233, 220, 1)', scrub: 'rgba(222, 232, 204, 1)', glacier: 'rgba(250, 252, 255, 1)'}
};

const out = layers('basemap', TOPO, {lang: 'en'});
const header = '// GENERATED by app/map/generate-basemap-layers.mjs from @protomaps/basemaps 5.7.2 (BSD-3-Clause).\n' +
  '// Do not edit by hand; change the TOPO flavor in the generator or override in style.js.\n';
const target = fileURLToPath(new URL('./basemap-layers.js', import.meta.url));
writeFileSync(target, `${header}export default ${JSON.stringify(out)};\n`);
console.log(`wrote ${out.length} layers to ${target}`);
